export type AppLanguage = keyof typeof catalogs
export type TranslationKey = keyof typeof catalogs.en
export type Translate = (key: TranslationKey, values?: Record<string, string | number>) => string
export const languages: { code: AppLanguage; label: string }[] = [{ code: "en", label: "English" }, { code: "de", label: "Deutsch" }, { code: "ar", label: "العربية" }, { code: "da", label: "Dansk" }]
const complete: Record<AppLanguage, Record<TranslationKey,string>> = catalogs
export function translate(language: AppLanguage, key: TranslationKey, values: Record<string,string | number> = {}) {
 return Object.entries(values).reduce((message,[name,value]) => message.replaceAll(`{${name}}`,String(value)), complete[language][key])
}
